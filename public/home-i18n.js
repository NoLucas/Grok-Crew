export const HOME_COPY = { en, ko, zh, ja };

export function pickHomeLang(value) {
  const lang = String(value || '').slice(0, 2).toLowerCase();
  return HOME_LANGS.includes(lang) ? lang : '';
}

export function readQueryLang(search = '') {
  try {
    return pickHomeLang(new URLSearchParams(search).get('lang'));
  } catch {
    return '';
  }
}

export function readSavedLang(storage) {
  try {
    return pickHomeLang(storage?.getItem?.(HOME_LANG_KEY));
  } catch {
    return '';
  }
}

export function homeCopy(lang) {
  return HOME_COPY[pickHomeLang(lang) || 'en'];
}

function setMeta(selector, attr, value) {
  const el = document.querySelector(selector);
  if (el) el.setAttribute(attr, value);
}

export function applyHomeLanguage(lang) {
  const resolved = pickHomeLang(lang) || 'en';
  const pack = HOME_COPY[resolved];
  document.documentElement.lang = resolved;
  document.documentElement.setAttribute('data-home-lang', resolved);
  document.title = pack.metaTitle;
  setMeta('meta[name="description"]', 'content', pack.metaDescription);
  setMeta('meta[property="og:title"]', 'content', pack.metaTitle);
  setMeta('meta[property="og:description"]', 'content', pack.metaDescription);
  setMeta('meta[name="twitter:title"]', 'content', pack.metaTitle);
  setMeta('meta[name="twitter:description"]', 'content', pack.metaDescription);
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (key && pack[key] != null) el.textContent = pack[key];
  });
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    const key = el.getAttribute('data-i18n-html');
    if (key && pack[key] != null) el.innerHTML = pack[key];
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    const key = el.getAttribute('data-i18n-aria');
    if (key && pack[key] != null) el.setAttribute('aria-label', pack[key]);
  });
  document.querySelectorAll('[data-i18n-alt]').forEach((el) => {
    const key = el.getAttribute('data-i18n-alt');
    if (key && pack[key] != null) el.setAttribute('alt', pack[key]);
  });
  document.querySelectorAll('[data-lang-btn]').forEach((el) => {
    el.setAttribute('aria-pressed', el.getAttribute('data-lang-btn') === resolved ? 'true' : 'false');
  });
  return resolved;
}
